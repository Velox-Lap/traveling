function buildStory(story, storyIndex) {
  nodes = {};
  sceneCount = 15 + (storyIndex % 6);
  stanceCounts = { truth: 0, care: 0, self: 0 };
  lastStance = null;
  currentNodeId = "scene-0";
  history = [];

  sceneBeats.slice(0, sceneCount).forEach((beat, index) => {
    const isFinalScene = index === sceneCount - 1;
    const choices = choiceSets[index % choiceSets.length].map((choice, choiceIndex) => ({
      label: choice.label,
      stance: choice.stance,
      next: isFinalScene ? `ending-${choiceIndex}` : `scene-${index + 1}`
    }));
    const text = [];

    if (index === 0) text.push(story.opening);
    text.push(beat.text);
    if (index === 2 || index === Math.floor(sceneCount / 2)) {
      text.push(story.complication);
    }
    if (lastStance) text.push(sceneReactions[lastStance]);
    if (index === sceneCount - 2) {
      text.push("ก่อนถึงจุดจบ คุณยังไม่ต้องมีคำตอบสมบูรณ์ แค่เลือกสิ่งที่พร้อมรับผิดชอบในตอนนี้");
    }

    createNode(`scene-${index}`, {
      stage: index + 1,
      title: index === 0 ? story.title : beat.title,
      text,
      choices,
      finalScene: isFinalScene
    });
  });

  for (let endingIndex = 0; endingIndex < 3; endingIndex += 1) {
    createNode(`ending-${endingIndex}`, {
      ending: true,
      endingIndex,
      title: "",
      text: []
    });
  }
}

