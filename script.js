function goToNode(nextNodeId, stance) {
  history.push({
    nodeId: currentNodeId,
    stanceCounts: { ...stanceCounts },
    lastStance
  });
  stanceCounts[stance] += 1;
  lastStance = stance;
  currentNodeId = nextNodeId;
  renderNode();
}

function goBack() {
  const previous = history.pop();
  if (!previous) return;
  currentNodeId = previous.nodeId;
  stanceCounts = previous.stanceCounts;
  lastStance = previous.lastStance;
  renderNode();
}

function renderNode() {
  const node = nodes[currentNodeId];
  if (!node) {
    throw new Error(`Story node "${currentNodeId}" does not exist.`);
  }

  const story = stories[activeStoryIndex];
  progressLabel.textContent = story.title;
  progressCount.textContent = node.ending
    ? `บทสรุป · ${sceneCount} ฉาก`
    : `ฉาก ${String(node.stage).padStart(2, "0")} / ${sceneCount}`;
  sceneKicker.textContent = node.ending ? "บทสรุปของเส้นทางนี้" : `ฉากที่ ${String(node.stage).padStart(2, "0")}`;
  sceneTitle.textContent = node.ending
    ? endingReflections[winningStance()].title
    : node.title;
  sceneText.replaceChildren();
  const paragraphs = node.ending
    ? [
        endingReflections[winningStance()].text,
        story.insight,
        `ในเรื่องนี้ คุณเลือกเดินผ่าน ${sceneCount} ฉาก ด้วยการตัดสินใจที่เป็นของคุณเอง ไม่มีผลลัพธ์ไหนนิยามตัวคุณได้ทั้งหมด`,
        `ลองถามตัวเองอย่างตรงไปตรงมาว่า: ${story.question}`
      ]
    : [...node.text];
  if (!node.ending && lastStance) {
    paragraphs.push(sceneReactions[lastStance]);
  }
  for (const paragraph of paragraphs) {
    const element = document.createElement("p");
    element.textContent = paragraph;
    sceneText.append(element);
  }
  storyCard.classList.remove("is-changing");
  void storyCard.offsetWidth;
  storyCard.classList.add("is-changing");
  worldSymbol.classList.remove("is-arriving");
  void worldSymbol.offsetWidth;
  worldSymbol.classList.add("is-arriving");

  choicesContainer.replaceChildren();
  endingActions.hidden = !node.ending;
  backButton.disabled = history.length === 0;
  window.scrollTo({ top: 0, behavior: reducedMotion.matches ? "auto" : "smooth" });

  if (node.ending) return;

  for (const choice of node.choices) {
    if (!nodes[choice.next]) {
      throw new Error(`Choice destination "${choice.next}" does not exist.`);
    }

    const button = document.createElement("button");
    button.className = "choice-button";
    button.type = "button";
    const label = document.createElement("span");
    label.textContent = choice.label;
    const arrow = document.createElement("span");
    arrow.className = "choice-arrow";
    arrow.setAttribute("aria-hidden", "true");
    arrow.textContent = "→";
    button.append(label, arrow);
    button.addEventListener("click", () => {
      playSparkBurst(button, 17, 1900);
      maybeCatJump(button);
      goToNode(choice.next, choice.stance);
    });
    bindTilt(button, 4);
    choicesContainer.append(button);
  }
}

function winningStance() {
  return ["truth", "care", "self"].reduce((winner, stance) =>
    stanceCounts[stance] > stanceCounts[winner] ? stance : winner
  , lastStance || "truth");
}

